package config

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// With INTERNAL_ALERT_TOKEN unset the backend generates the service token into
// the volume it shares with the WAF, so a manual install (cp .env.example .env)
// gets working WAF alerts and WAF controls instead of an empty credential.
func TestServiceTokenIsGeneratedIntoTheSharedVolumeWhenUnset(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "alert_token")

	tok := serviceToken("", path)
	if len(tok) != 64 || encryptionKeyError(tok) != nil {
		t.Fatalf("generated token %q is not 64 hex characters", tok)
	}
	got, err := os.ReadFile(path)
	if err != nil || strings.TrimSpace(string(got)) != tok {
		t.Fatalf("token not persisted: %q, %v", got, err)
	}
	if fi, _ := os.Stat(path); fi.Mode().Perm() != 0o644 {
		t.Errorf("mode %v, want 0644 so the WAF (another uid) can read it", fi.Mode().Perm())
	}
	if again := serviceToken("", path); again != tok {
		t.Errorf("second start rotated the token: %q then %q", tok, again)
	}
}

// The environment wins: an operator who set INTERNAL_ALERT_TOKEN keeps it, and
// nothing is written.
func TestServiceTokenFromTheEnvironmentWins(t *testing.T) {
	path := filepath.Join(t.TempDir(), "alert_token")
	if got := serviceToken("  set-by-operator  ", path); got != "set-by-operator" {
		t.Errorf("got %q, want the environment's value trimmed", got)
	}
	if _, err := os.Stat(path); err == nil {
		t.Error("a token file was written although the environment set one")
	}
}

// A malformed file is replaced: the token is the services' own credential,
// regenerated by the one that owns it and read again by the other.
func TestMalformedServiceTokenFileIsReplaced(t *testing.T) {
	path := filepath.Join(t.TempDir(), "alert_token")
	_ = os.WriteFile(path, []byte("short"), 0o644)
	if tok := serviceToken("", path); len(tok) != 64 {
		t.Errorf("malformed file kept: %q", tok)
	}
}

// Without the shared volume (a hand-written compose file) nothing can be
// shared, so the token stays empty and the existing warning applies.
func TestServiceTokenStaysEmptyWithoutTheVolume(t *testing.T) {
	path := filepath.Join(t.TempDir(), "not-mounted", "alert_token")
	if tok := serviceToken("", path); tok != "" {
		t.Errorf("got %q without the volume directory; want empty", tok)
	}
}
